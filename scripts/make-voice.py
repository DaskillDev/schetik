"""Records Счётик's voice: every phrase the game says, spoken by a neural Russian voice,
packed into one audio sprite (assets/voice/voice.mp3) plus a map of where each clip sits
(src/lib/voice-map.ts).

Run:  pip install edge-tts imageio-ffmpeg
      python scripts/make-voice.py

Keys are normalised text (lower case, no punctuation), the same way src/lib/speech.ts
normalises what the game wants to say. Numbers are keyed "#7", "#300", "#1000".
"""

import asyncio
import os
import re
import subprocess
import sys

import edge_tts
import imageio_ffmpeg

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VOICE = "ru-RU-SvetlanaNeural"
RATE = "-8%"
PITCH = "+12Hz"
SR = 24000
GAP = 0.25  # silence between clips in the sprite, seconds

PHRASES = [
    # questions
    "Сколько будет", "плюс", "минус", "умножить на", "разделить на", "равно", "окошко", "и",
    "Сравни:", "Какое число в окошке?", "Посчитай. Сколько всего?", "Посчитай. Сколько тут?",
    "меньше", "больше",
    # answers
    "Молодец!", "Верно!", "Супер!", "Так держать!", "Отлично!", "Умница!",
    "подряд!", "Почти! Правильно:",
    # results
    "Идеально!", "Отличный результат!", "Хорошо!", "Попробуем ещё раз?", "Открыт новый уровень!",
    "Новый рекорд!", "Все шарики лопнули!", "Все пары найдены!", "Все покупки сделаны!",
    # shop
    "Мороженое", "Яблоко", "Сок", "Шарик", "Печенье", "Карандаш", "Мишка", "Мяч", "Бананы",
    "Тетрадка", "Краски", "Шоколадка", "стоит", "рубль", "рубля", "рублей",
    "Заплати ровно столько!", "Спасибо за покупку!", "Многовато! Убери лишние монетки.",
    "Маловато! Добавь ещё монеток.",
    # greeting
    "Привет!", "Ты занимаешься", "день", "дня", "дней", "Не прерывай серию!",
    "Я Счётик. Давай считать вместе!", "Отлично позанимались сегодня! Ещё разок?",
]

ONES = ["ноль", "один", "два", "три", "четыре", "пять", "шесть", "семь", "восемь", "девять", "десять",
        "одиннадцать", "двенадцать", "тринадцать", "четырнадцать", "пятнадцать", "шестнадцать",
        "семнадцать", "восемнадцать", "девятнадцать"]
TENS = {20: "двадцать", 30: "тридцать", 40: "сорок", 50: "пятьдесят", 60: "шестьдесят",
        70: "семьдесят", 80: "восемьдесят", 90: "девяносто"}
HUNDREDS = {100: "сто", 200: "двести", 300: "триста", 400: "четыреста", 500: "пятьсот",
            600: "шестьсот", 700: "семьсот", 800: "восемьсот", 900: "девятьсот", 1000: "тысяча"}


def words(n: int) -> str:
    if n < 20:
        return ONES[n]
    t, o = n // 10 * 10, n % 10
    return TENS[t] + (" " + ONES[o] if o else "")


def key(text: str) -> str:
    return " ".join(re.sub(r"[^\w\s]", " ", text.lower()).split())


def clips():
    out = [(key(p), p) for p in PHRASES]
    out += [(f"#{n}", words(n)) for n in range(100)]
    out += [(f"#{n}", w) for n, w in HUNDREDS.items()]
    return out


async def record(text: str, path: str):
    for attempt in range(5):
        try:
            await edge_tts.Communicate(text, VOICE, rate=RATE, pitch=PITCH).save(path + ".part")
            os.replace(path + ".part", path)
            return
        except Exception:
            if attempt == 4:
                raise
            await asyncio.sleep(2 + attempt * 3)


def pcm(path: str) -> bytes:
    """Decode to 16-bit mono PCM with leading/trailing silence trimmed."""
    trim = "silenceremove=start_periods=1:start_threshold=-50dB:start_silence=0.03"
    cmd = [imageio_ffmpeg.get_ffmpeg_exe(), "-v", "error", "-i", path,
           "-af", f"{trim},areverse,{trim},areverse", "-ac", "1", "-ar", str(SR), "-f", "s16le", "-"]
    return subprocess.run(cmd, check=True, capture_output=True).stdout


async def main():
    tmp = os.path.join(ROOT, ".voice-cache")
    os.makedirs(tmp, exist_ok=True)
    items = clips()
    for i, (k, text) in enumerate(items):
        path = os.path.join(tmp, f"{i:03d}.mp3")
        if not os.path.exists(path):
            await record(text, path)
        sys.stdout.write(f"\r{i + 1}/{len(items)}")
    print()

    gap = b"\0\0" * int(SR * GAP)
    sprite = bytearray(gap)
    table = {}
    for i, (k, _) in enumerate(items):
        data = pcm(os.path.join(tmp, f"{i:03d}.mp3"))
        start = len(sprite) / 2 / SR
        sprite += data + gap
        table[k] = (round(start, 3), round(len(data) / 2 / SR, 3))

    out = os.path.join(ROOT, "assets", "voice", "voice.mp3")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    cmd = [imageio_ffmpeg.get_ffmpeg_exe(), "-v", "error", "-y", "-f", "s16le", "-ar", str(SR), "-ac", "1",
           "-i", "-", "-b:a", "48k", out]
    subprocess.run(cmd, input=bytes(sprite), check=True)

    lines = ",\n".join(f"  {k!r}: [{s}, {d}]".replace("'", '"') for k, (s, d) in table.items())
    with open(os.path.join(ROOT, "src", "lib", "voice-map.ts"), "w", encoding="utf-8") as f:
        f.write("// Generated by scripts/make-voice.py — do not edit by hand.\n")
        f.write("/** Where each clip sits in assets/voice/voice.mp3: [start, duration] in seconds. */\n")
        f.write(f"export const VOICE_MAP: Record<string, [number, number]> = {{\n{lines},\n}};\n")
    print(f"{len(table)} clips, {os.path.getsize(out) // 1024} KB")


asyncio.run(main())
